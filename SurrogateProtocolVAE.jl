abstract type AbstractProtocol end

"""
$TYPEDEF

A protocol simulating the behavior of a quantum network, trained using a 
variational autoencoder (VAE) architecture. The VAE is designed to learn a 
latent representation of the protocol's behavior based on training data 
consisting of time-series data of observables from the quantum network 
simulations. The surrogate protocol can then be used to generate new time-series 
data that mimics the behavior of the original protocol, allowing for faster 
simulations and analysis.

$FIELDS
"""
@kwdef struct SurrogateProtocolVAE <: AbstractProtocol
    """time-and-schedule-tracking instance from `ConcurrentSim`"""
    simulation::Simulation
    """Path containing the training data (can be a directory or a specific file)."""
    training_data_path::Union{String,Nothing} = nothing
    """Vector containing all the data that is to be used for training."""
    training_data::Matrix{Float64}
    """Number of simulated instances of entanglement consumption."""
    simulation_window_size::Int
    """Dimensionality of the latent space representation."""
    latent_dim::Int = 1
    """Number of latent layers in the encoder and decoder chains of the VAE."""
    latent_layers::Int = 1
    """Encoder chain of the VAE, responsible for encoding time-series data into a latent representation."""
    encoders::Tuple{Chain}
    """Decoder chain of the VAE, responsible for generating time-series data from the latent representation."""
    decoders::Tuple{Chain}
    """Weighting factor for the KL divergence term in the VAE loss function."""
    β::Union{Float64,Vector{Float64}} = 1.0
    """Number of training epochs for the VAE."""
    epochs::Int = 100
    """Batch size for training the VAE."""
    batchsize::Int = 32
    """Flag indicating whether to shuffle the training data during training."""
    shuffle::Bool = true
    """Optimizer used to train the VAE."""
    optimiser::Union{Optimisers.AbstractRule, Flux.Optimise.AbstractOptimiser} = Adam(0.01f0)
    """Hardware device (CPU or GPU) on which to perform training and inference."""
    device::Flux.MLDataDevices.AbstractDevice = Flux.cpu_device()
    """Stores the simulated time-series data generated by the surrogate protocol after training."""
    _log::Vector{Tuple} = Vector{Tuple}[]
end

struct VariationalAutoencoder
    encoders::Tuple
    decoders::Tuple
    β::Float64
    device::Flux.MLDataDevices.AbstractDevice
end

Functors.@functor VariationalAutoencoder (encoders, decoders)

function sample_latent(μ, σ)
    ϵ = Flux.randn_like(μ, size(μ))
    return μ .+ σ .* ϵ
end

function _encode(encoders::Tuple, x, latent_dim, num_latent_layers)
    batch_size = size(x, 2)
    
    μ_buf = Zygote.Buffer(x, eltype(x), latent_dim, num_latent_layers, batch_size)
    σ_buf = Zygote.Buffer(x, eltype(x), latent_dim, num_latent_layers, batch_size)
    logσ²_buf = Zygote.Buffer(x, eltype(x), latent_dim, num_latent_layers, batch_size)
    z_buf = Zygote.Buffer(x, eltype(x), latent_dim, num_latent_layers, batch_size)

    enc_out = encoders[1](x)
    μ_buf[:, 1, :] = enc_out[1:latent_dim, :]
    logσ²_buf[:, 1, :] = enc_out[(latent_dim+1):end, :]
    σ_buf[:, 1, :] = exp.(logσ²_buf[:, 1, :] .* 0.5f0)
    z_buf[:, 1, :] = sample_latent(μ_buf[:, 1, :], σ_buf[:, 1, :])

    for i in 2:num_latent_layers
        enc_out = encoders[i](z_buf[:, i-1, :])
        μ_buf[:, i, :] = enc_out[1:latent_dim, :]
        logσ²_buf[:, i, :] = enc_out[(latent_dim+1):end, :]
        σ_buf[:, i, :] = exp.(logσ²_buf[:, i, :] .* 0.5f0)
        z_buf[:, i, :] = sample_latent(μ_buf[:, i, :], σ_buf[:, i, :])
    end

    return copy(μ_buf), copy(σ_buf), copy(logσ²_buf), copy(z_buf)
end

function _decode(decoders::Tuple, z, latent_dim, num_latent_layers)
    batch_size = size(z, 3)
    
    μ_buf = Zygote.Buffer(z, eltype(z), latent_dim, num_latent_layers, batch_size)
    σ_buf = Zygote.Buffer(z, eltype(z), latent_dim, num_latent_layers, batch_size)
    logσ²_buf = Zygote.Buffer(z, eltype(z), latent_dim, num_latent_layers, batch_size)

    μ_buf[:, num_latent_layers, :] = Flux.zeros_like(z, (latent_dim, batch_size))
    σ_buf[:, num_latent_layers, :] = Flux.ones_like(z, (latent_dim, batch_size))
    logσ²_buf[:, num_latent_layers, :] = Flux.zeros_like(z, (latent_dim, batch_size))

    for i in 2:num_latent_layers
        idx = num_latent_layers - i + 1
        dec_out = decoders[idx+1](z[:, idx+1, :])
        μ_buf[:, idx, :] = dec_out[1:latent_dim, :]
        logσ²_buf[:, idx, :] = dec_out[(latent_dim+1):end, :]
        σ_buf[:, idx, :] = exp.(logσ²_buf[:, idx, :] .* 0.5f0)
    end

    x̂ = decoders[1](z[:, 1, :])
    return copy(μ_buf), copy(σ_buf), copy(logσ²_buf), x̂
end

function vae_loss(model::VariationalAutoencoder, input_weights, x)
    batch_size = size(x, 2)
    latent_dim = size(model.decoders[1][1].weight, 2)
    num_latent_layers = length(model.decoders)

    μ_enc, σ_enc, logσ²_enc, z = _encode(model.encoders, x, latent_dim, num_latent_layers)
    μ_dec, σ_dec, logσ²_dec, x̂ = _decode(model.decoders, z, latent_dim, num_latent_layers)

    recon_loss = 0.5f0 .* sum(input_weights .* ((x .- x̂).^2))   
    kl_loss = 0.5f0 .* sum(logσ²_dec .- logσ²_enc .+ (σ_enc.^2 .+ (μ_enc .- μ_dec).^2) ./ σ_dec.^2 .- 1.0f0)

    return (recon_loss + model.β * kl_loss) / batch_size
end

struct VAETrainingLog
    loss::Vector{Float64}
    loss_grad_norm::Vector{Float64}
end

function _train!(protocol::SurrogateProtocolVAE, β::Number; print_log::Bool = true)
    model = VariationalAutoencoder(
        protocol.encoders, 
        protocol.decoders, 
        β,
        protocol.device
    )
    model_train_device = model |> protocol.device
    opt_state = Flux.setup(protocol.optimiser, model_train_device)

    training_data_on_device = Float64.(protocol.training_data) |> protocol.device
    loader = Flux.DataLoader(
        training_data_on_device, 
        batchsize=protocol.batchsize, 
        shuffle=protocol.shuffle,
        parallel=true
    )

    input_weights = [1.0 / var(protocol.training_data[i,:]) for i in 1:size(protocol.training_data,1)]
    input_weights[input_weights .> 1.0E9] .= 0.0 # ignore nearly deterministic inputs
    input_weights_device = input_weights |> protocol.device

    training_log = VAETrainingLog(
        zeros(Float64,protocol.epochs),
        zeros(Float64,protocol.epochs)
    )

    if print_log; println("Training VAE... (β = $β)") end
    for epoch in 1:protocol.epochs
        epoch_loss = 0f0
        total_grad_norm = 0f0

        for x_batch in loader
            loss, grads = Flux.withgradient(model_train_device) do m
                vae_loss(m, input_weights_device, x_batch)
            end

            flat_grads, _ = Flux.destructure(grads[1])
            batch_grad_norm = sqrt(sum(abs2, flat_grads))

            Flux.update!(opt_state, model_train_device, grads[1])
            epoch_loss += loss
            total_grad_norm += batch_grad_norm
        end

        training_log.loss[epoch] = epoch_loss / length(loader)
        training_log.loss_grad_norm[epoch] = total_grad_norm / length(loader)

        if epoch % 5 == 0 || epoch == 1
            average_loss = training_log.loss[epoch]
            average_grad_norm = training_log.loss_grad_norm[epoch]
            if print_log; println("Epoch $epoch | Average Loss: $average_loss | Grad Norm: $average_grad_norm") end
        end
    end
    if print_log; println("Training complete!") end

    return training_log
end

function _train!(protocol::SurrogateProtocolVAE, β::Vector; print_log::Bool = true)
    training_log = nothing
    for i in eachindex(β)
        training_log = _train!(protocol,Float64(β[i]) |> protocol.device; print_log = print_log)
    end

    return training_log
end

function train!(protocol::SurrogateProtocolVAE; print_log::Bool = true)
    return _train!(protocol, protocol.β; print_log = print_log)
end

@resumable function (protocol::SurrogateProtocolVAE)()
    while true
    end
end

function decode(protocol::SurrogateProtocolVAE, z)
    num_latent_layers = length(protocol.decoders)

    for i in 1:(num_latent_layers-1)
        dec_out = protocol.decoders[num_latent_layers-i+1](z)
        z = sample_latent(dec_out[1:protocol.latent_dim], exp.(dec_out[(protocol.latent_dim+1):end] .* 0.5f0))
    end

    return protocol.decoders[1](z) |> protocol.device
end

function encode(protocol::SurrogateProtocolVAE, x)
    num_latent_layers = length(protocol.encoders)

    enc_out = protocol.encoders[1](x)
    z = sample_latent(enc_out[1:protocol.latent_dim,:], exp.(enc_out[(protocol.latent_dim+1):end,:] .* 0.5f0))
    
    for i in 2:num_latent_layers
        enc_out = protocol.encoders[i](z)
        z = sample_latent(enc_out[1:protocol.latent_dim,:], exp.(enc_out[(protocol.latent_dim+1):end,:] .* 0.5f0))
    end

    return z
end

function (protocol::SurrogateProtocolVAE)(n_samples::Int)
    window_size = size(protocol.training_data)[1]
    sim_log = zeros(Float64,n_samples,window_size)

    for i in 1:n_samples
        z = rand(Normal(0.0,1.0),protocol.latent_dim)
        sim_log[i,:] = decode(protocol,z)
    end

    return sim_log
end

@enum ActivationFunction::UInt8 begin
    _relu       = 0
    _gelu       = 1
    _tanh       = 2
    _sigmoid    = 3
    _softmax    = 4
    _leakyrelu  = 5
    _elu        = 6
    _swish      = 7
    _identity   = 8
end

struct LayerParameters
    node_bias::Vector{Float64}
    node_weights::Matrix{Float64}
    activation_function::ActivationFunction
end

struct ChainParameters
    layers::Vector{LayerParameters}
end

struct VariationalAutoencoderParameters
    encoders::Vector{ChainParameters}
    decoders::Vector{ChainParameters}
end

function layer_parameter(layer::Dense)
    activation_function_map = Dict(
        relu => _relu,
        gelu => _gelu,
        tanh => _tanh,
        sigmoid => _sigmoid,
        softmax => _softmax,
        leakyrelu => _leakyrelu,
        elu => _elu,
        swish => _swish,
        identity => _identity
    )

    if hasproperty(layer,:σ)
        return LayerParameters(
            layer.bias,
            layer.weight,
            activation_function_map[layer.σ]
        )
    end

    return LayerParameters(
        layer.bias,
        layer.weight,
        activation_function_map[identity]
    )
end

function layer_parameter(layer::LayerParameters)
    activation_function_map = Dict(
        _relu => relu,
        _gelu => gelu,
        _tanh => tanh,
        _sigmoid => sigmoid,
        _softmax => softmax,
        _leakyrelu => leakyrelu,
        _elu => elu,
        _swish => swish,
        _identity => identity
    )

    return Dense(layer.node_weights, layer.node_bias, activation_function_map[layer.activation_function])
end

function chain_parameters(chain::Chain)
    layers = Vector{LayerParameters}(undef, length(chain))
    for i in eachindex(chain)
        layers[i] = layer_parameter(chain[i])
    end

    return ChainParameters(layers)
end

function variational_autoencoder_parameters(prot::SurrogateProtocolVAE)
    return VariationalAutoencoderParameters(
        [chain_parameters(encoder) for encoder in prot.encoders],
        [chain_parameters(decoder) for decoder in prot.decoders]
    )
end

