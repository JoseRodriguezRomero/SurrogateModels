abstract type AbstractProtocol end

"""
$TYPEDEF

A protocol simulating the behavior of a quantum network, trained using a variational autoencoder (VAE) architecture. The VAE is designed to learn a latent representation of the protocol's behavior based on training data consisting of time-series data of observables from the quantum network simulations. The surrogate protocol can then be used to generate new time-series data that mimics the behavior of the original protocol, allowing for faster simulations and analysis.

$FIELDS
"""
@kwdef struct SurrogateProtocolVAE <: AbstractProtocol
    """time-and-schedule-tracking instance from `ConcurrentSim`"""
    simulation::Simulation
    """Directory containing the training data (HDF5 files with simulation logs)."""
    training_data_directory::String
    """Vector containing all the data that is to be used for training."""
    training_data::Matrix{Float64}
    """Number of simulated instances of entanglement consumption."""
    simulation_window_size::Int
    """Dimensionality of the latent space representation."""
    latent_dim::Int
    """Decoder chain of the VAE, responsible for generating time-series data from the latent representation."""
    decoder_chain::Chain
    """Encoder chain of the VAE, responsible for encoding time-series data into a latent representation."""
    encoder_chain::Chain
    """Dense layer for computing the mean (μ) of the latent distribution."""
    μ_layer::Dense
    """Dense layer for computing the standard deviation (σ) of the latent distribution."""
    σ_layer::Dense
    """Weighting factor for the KL divergence term in the VAE loss function."""
    β::Union{Float64,Vector{Float64}} = 1.0
    """Number of training epochs for the VAE."""
    epochs::Int = 100
    """Batch size for training the VAE."""
    batchsize::Int = 32
    """Flag indicating whether to shuffle the training data during training."""
    shuffle::Bool = true
    """Optimizer used to train the VAE."""
    optimiser::Union{Optimisers.AbstractRule, Flux.Optimise.AbstractOptimiser} = Adam(0.01f0)
    """Hardware device (CPU or GPU) on which to perform training and inference."""
    device::Flux.MLDataDevices.AbstractDevice = Flux.cpu_device()
    """Stores the simulated time-series data generated by the surrogate protocol after training."""
    _log::Vector{Tuple} = Vector{Tuple}[]
end

function load_training_data(training_data_directory::String)
    file_names = filter(x -> endswith(x, ".h5"), readdir(training_data_directory, join=true))
    training_data = Vector{Matrix{Float64}}(undef, length(file_names))

    for sample_id in eachindex(file_names)
        try
            consumer_log = load_entanglement_consumer_log(file_names[sample_id])
            training_data[sample_id] = hcat(consumer_log.simulation_log.time, consumer_log.simulation_log.state')
        catch e
            throw(e)
        end
    end

    return training_data
end

function SurrogateProtocolVAE(simulation::Simulation, training_data_directory::String; simulation_window_size::Int = 1, latent_dim::Int = 2, kwargs...)
    raw_training_data = load_training_data(training_data_directory)
    reshaped_training_data = Vector{Matrix{Float64}}(undef, length(raw_training_data))

    for i in eachindex(raw_training_data)
        total_rows = size(raw_training_data[i], 1)
        total_windows = total_rows - simulation_window_size

        raw_mat = raw_training_data[i]
        t_diff_mat = zeros(Float64, size(raw_mat)[1]-1, size(raw_mat)[2])
        t_diff_mat[:,1] = diff(raw_mat[:,1])
        t_diff_mat[:,2:end] = raw_mat[1:(end-1),2:end]

        reshaped_matrix = [vec(t_diff_mat[j:(j + simulation_window_size - 1), :]) for j in 1:total_windows]
        reshaped_training_data[i] = collect(transpose(reduce(hcat, reshaped_matrix)))
    end

    reshaped_training_data = collect(transpose(reduce(vcat,reshaped_training_data)))
    reshaped_training_data = Float64.(reshaped_training_data)
    encoder_input_size = size(reshaped_training_data)[1]
    encoder_chain = Chain(
        Dense(encoder_input_size, 32, relu), 
        Dense(32, 32, relu),
        Dense(32, 32, relu),
        Parallel(vcat, 
            Dense(32 => latent_dim), 
            Dense(32 => latent_dim)
        )
    ) |> f64
    decoder_chain = Chain(
        Dense(latent_dim, 32, relu), 
        Dense(32, 32, relu),
        Dense(32, 32, relu), 
        Dense(32, encoder_input_size)
    ) |> f64
    μ_layer = Dense(32, latent_dim) |> f64
    σ_layer = Dense(32, latent_dim) |> f64

    return SurrogateProtocolVAE(;
        simulation = simulation,
        training_data_directory = training_data_directory,
        training_data = reshaped_training_data,
        simulation_window_size = simulation_window_size, 
        latent_dim = latent_dim, 
        decoder_chain = decoder_chain, 
        encoder_chain = encoder_chain, 
        μ_layer = μ_layer, 
        σ_layer = σ_layer,
        kwargs...
    )
end

struct VariationalAutoencoder 
    encoder::Chain
    decoder::Chain
    β::Float64
    device::Flux.MLDataDevices.AbstractDevice
end

Flux.@layer VariationalAutoencoder

function sample_latent(μ, σ, device)
    ϵ = randn(Float64, size(μ)) |> device
    return μ .+ σ .* ϵ
end

function vae_loss(m::VariationalAutoencoder, x)
    latent_dim = size(m.decoder[1].weight,2)
    batch_size = size(x,2)

    enc_out = m.encoder(x)
    μ = enc_out[1:latent_dim, :]
    logσ² = enc_out[latent_dim+1:end, :]
    z = sample_latent(μ, exp.(logσ² .* 0.5f0), m.device)
    x_hat = m.decoder(z)

    recon_loss = 0.5f0 * sum((x .- x_hat).^2) / batch_size
    kl_loss = -0.5f0 * sum(1.0f0 .+ logσ² .- μ.^2 .- exp.(logσ²)) / batch_size
    
    return recon_loss + m.β * kl_loss
end

function _train!(protocol::SurrogateProtocolVAE, β::Number)
    model = VariationalAutoencoder(
        protocol.encoder_chain, 
        protocol.decoder_chain, 
        β,
        protocol.device
    )
    model_train_device = model |> protocol.device
    opt_state = Flux.setup(protocol.optimiser, model_train_device)

    training_data_on_device = Float64.(protocol.training_data) |> protocol.device
    loader = Flux.DataLoader(
        training_data_on_device, 
        batchsize=protocol.batchsize, 
        shuffle=protocol.shuffle,
        parallel=true
    )

    println("Training VAE... (β = $β)")
    for epoch in 1:protocol.epochs
        epoch_loss = 0f0

        for x_batch in loader
            loss, grads = Flux.withgradient(model_train_device) do m
                vae_loss(m, x_batch)
            end

            Flux.update!(opt_state, model_train_device, grads[1])
            epoch_loss += loss
        end

        # Print progress every 5 epochs
        if epoch % 5 == 0 || epoch == 1
            average_loss = epoch_loss / length(loader)
            println("Epoch $epoch | Average Loss: $(round(average_loss, digits=4))")
        end
    end
    println("Training complete!")
end

function _train!(protocol::SurrogateProtocolVAE, β::Vector)
    for i in eachindex(β)
        _train!(protocol,Float64(β[i]) |> protocol.device)
    end
end

function train!(protocol::SurrogateProtocolVAE)
    _train!(protocol, protocol.β)
end

