function (protocol::SurrogateProtocolVAE)(n_samples::Int)
    window_size = size(protocol.training_data)[1]
    log = zeros(Float64,n_samples,window_size)

    for i in 1:n_samples
        log[i,:] = rand(Normal(0.0,1.0),window_size)
    end

    return log
end

