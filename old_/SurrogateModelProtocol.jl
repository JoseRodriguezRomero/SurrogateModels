module SurrogateModelProtocol

using Flux
using Zygote
using MLUtils

using QuantumSavory
using DocStringExtensions
using ConcurrentSim, ResumableFunctions

export 
    AbstractSurrogateProtocol
abstract type AbstractProtocol end
abstract type AbstractSurrogateModel end

struct TrainingLog
    loss::Vector{Float64}
    loss_grad_norm::Vector{Float64}
end

"""
$TYPEDEF

A protocol simulating the behavior of a quantum network, trained using a 
unespecified architecture. The abstract surrgorate is designed to learn a latent 
representation of the protocol's behavior based on training data consisting of 
time-series data of observables from the quantum network simulations. The 
surrogate protocol can then be used to generate new time-series data that mimics 
the behavior of the original protocol, allowing for faster simulations and 
analysis.

$FIELDS
"""
@kwdef struct SurrogateModelProtocol <: AbstractProtocol
    """time-and-schedule-tracking instance from `ConcurrentSim`"""
    simulation::Simulation
    """Path containing the training data (can be a directory or a specific file)."""
    training_data_path::Union{String,Nothing} = nothing
    """Vector containing all the data that is to be used for training."""
    training_data::Matrix{Float64}
    """Number of simulated instances of entanglement consumption."""
    simulation_window_size::Int
    """Number of training epochs for the surrogate."""
    epochs::Int = 100
    """Batch size for training the surrogate."""
    batchsize::Int = 32
    """Flag indicating whether to shuffle the training data during training."""
    shuffle::Bool = true
    """Optimizer used to train the surrogate."""
    optimiser::Union{Optimisers.AbstractRule, Flux.Optimise.AbstractOptimiser} = Adam(0.01f0)
    """Hardware device (CPU or GPU) on which to perform training and inference."""
    device::Flux.MLDataDevices.AbstractDevice = Flux.cpu_device()
    """Surrogate model architecture to be used."""
    model::AbstractSurrogateModel
    """Stores the simulated time-series data generated by the surrogate protocol after training."""
    _log::TrainingLog
end

function _train!(protocol::SurrogateModelProtocol, model::AbstractSurrogateModel; print_log::Bool = true)
    throw(MethodError(train!, (protocol, model; print_log = print_log)))
end

function train!(protocol::SurrogateModelProtocol; print_log::Bool = true)
    _train!(protocol, protocol.model; print_log = print_log)
end

function _eval(protocol::SurrogateModelProtocol, model::AbstractSurrogateModel, n_samples::Int)
    throw(MethodError(_eval, (protocol, model, n_samples)))
end

function (protocol::SurrogateModelProtocol)(n_samples::Int)
    return _eval(protocol, protocol.model, n_samples)
end

function load_data(training_data::Matrix, batch_size::Int, shuffle::Bool = false, parallel::Bool = true)
    if shuffle
        return Flux.DataLoader(
            shuffleobs(training_data), 
            batchsize = batch_size, 
            shuffle = shuffle,
            parallel = parallel
        )
    end

    return Flux.DataLoader(
        training_data, 
        batchsize = batch_size, 
        shuffle = shuffle,
        parallel = parallel
    )
end

function load_training_data(training_data_path::String)
    if isfile(training_data_path)
        consumer_log = EntanglementConsumerLog(training_data_path)
        training_data = hcat(consumer_log.simulation_log.time, consumer_log.simulation_log.state')
        return [training_data]
    else
        file_names = filter(x -> isfile(x), readdir(training_data_path, join=true))
        training_data = Vector{Matrix{Float64}}(undef, length(file_names))

        for sample_id in eachindex(file_names)
            consumer_log = EntanglementConsumerLog(file_names[sample_id])

            if !isnothing(consumer_log)
                training_data[sample_id] = hcat(consumer_log.simulation_log.time, consumer_log.simulation_log.state')
            else
                training_data[sample_id] = zeros(Float64,0,0)
            end
        end
    end

    return filter(x -> !isempty(x), training_data)
end

@enum ActivationFunction::UInt8 begin
    _relu       = 0
    _gelu       = 1
    _tanh       = 2
    _sigmoid    = 3
    _softmax    = 4
    _leakyrelu  = 5
    _elu        = 6
    _swish      = 7
    _identity   = 8
end

struct LayerParameters
    node_bias::Vector{Float64}
    node_weights::Matrix{Float64}
    activation_function::ActivationFunction
end

struct ChainParameters
    layers::Vector{LayerParameters}
end

function layer_parameter(layer::Dense)
    activation_function_map = Dict(
        relu => _relu,
        gelu => _gelu,
        tanh => _tanh,
        sigmoid => _sigmoid,
        softmax => _softmax,
        leakyrelu => _leakyrelu,
        elu => _elu,
        swish => _swish,
        identity => _identity
    )

    if hasproperty(layer,:σ)
        return LayerParameters(
            layer.bias,
            layer.weight,
            activation_function_map[layer.σ]
        )
    end

    return LayerParameters(
        layer.bias,
        layer.weight,
        activation_function_map[identity]
    )
end

function layer_parameter(layer::LayerParameters)
    activation_function_map = Dict(
        _relu => relu,
        _gelu => gelu,
        _tanh => tanh,
        _sigmoid => sigmoid,
        _softmax => softmax,
        _leakyrelu => leakyrelu,
        _elu => elu,
        _swish => swish,
        _identity => identity
    )

    return Dense(layer.node_weights, layer.node_bias, activation_function_map[layer.activation_function])
end

function chain_parameters(chain::Chain)
    layers = Vector{LayerParameters}(undef, length(chain))
    for i in eachindex(chain)
        layers[i] = layer_parameter(chain[i])
    end

    return ChainParameters(layers)
end

end