abstract type AbstractProtocol end

"""
$TYPEDEF

A protocol simulating the behavior of a quantum network, trained using a 
Diffusion Model (DM) architecture. The DM is designed to learn a latent 
representation of the protocol's behavior based on training data consisting of 
time-series data of observables from the quantum network simulations. The 
surrogate protocol can then be used to generate new time-series data that mimics 
the behavior of the original protocol, allowing for faster simulations and 
analysis.

$FIELDS
"""
@kwdef struct SurrogateProtocolDM <: AbstractProtocol
    """time-and-schedule-tracking instance from `ConcurrentSim`"""
    simulation::Simulation
    """Path containing the training data (can be a directory or a specific file)."""
    training_data_path::Union{String,Nothing} = nothing
    """Vector containing all the data that is to be used for training."""
    training_data::Matrix{Float64}
    """Number of simulated instances of entanglement consumption."""
    simulation_window_size::Int
    """Number of diffusion steps (number of steps in the Markov chain)."""
    T::Unsigned
    """Variance of the Gaussian noise added in each diffusion step."""
    β::Vector{Unsigned}
    """Neural network parametrizing the denoising model, that is, a model that probabilisitically undoes the Gaussian noise."""
    denoiser_model::Chain
    """Number of training epochs for the VAE."""
    epochs::Int = 100
    """Batch size for training the VAE."""
    batchsize::Int = 32
    """Flag indicating whether to shuffle the training data during training."""
    shuffle::Bool = true
    """Optimizer used to train the VAE."""
    optimiser::Union{Optimisers.AbstractRule, Flux.Optimise.AbstractOptimiser} = Adam(0.01f0)
    """Hardware device (CPU or GPU) on which to perform training and inference."""
    device::Flux.MLDataDevices.AbstractDevice = Flux.cpu_device()
    """Stores the simulated time-series data generated by the surrogate protocol after training."""
    _log::Vector{Tuple} = Vector{Tuple}[]
end

function SurrogateProtocolDM(T::Int, β_start::Float64=1.0E-4, β_end::Float64=0.02; kwargs...)
    β = Float32.(collect(range(β_start, β_end, length=T)))
    return SurrogateProtocolDM(; T = T, β = β, kwargs...)
end

struct DiffusionModel
    T::Unsigned
    α::Vector{Float64}
    ᾱ::Vector{Float64}
    β::Vector{Float64}
    denoiser_model::Chain
    device::Flux.MLDataDevices.AbstractDevice
end

function DiffusionModel(T::Unsigned, β::Vector{Float64}, denoiser_model::Chain, device::Flux.MLDataDevices.AbstractDevice)
    α = Float64(1.0) .- β,
    ᾱ = (cumprod(α))
    return DiffusionModel(T,α,ᾱ,β,denoiser_model,device)
end

struct DMTrainingLog
    loss::Vector{Float64}
    loss_grad_norm::Vector{Float64}
end

function forward_diffusion(model::DiffusionModel, x₀::AbstractMatrix, t::Vector{Int})
    ϵ = Flux.randn_like(x₀, size(x₀))
    ᾱₜ = reshape(model.ᾱ[t], 1, :)
    xₜ = sqrt.(ᾱₜ) .* x₀ + sqrt.(Float64(1.0) .- ᾱₜ) .* ϵ
    return xₜ, ϵ
end

function train!(protocol::SurrogateProtocolDM; print_log::Bool = true)
    model = DiffusionModel(
        protocol.T,
        protocol.β,
        protocol.denoiser_model,
        protocol.device
    )
    model_train_device = model |> protocol.device
    opt_state = Flux.setup(protocol.optimiser)
    batchsize_device = protocol.batchsize |> protocol.device
    training_data_device = Float64.(protocol.training_data) |> protocol.device

    loader = Flux.DataLoader(
        training_data_device, 
        batchsize = batchsize_device, 
        shuffle = false,
        parallel = true
    )
    loader_length = length(loader)
    loader_length_device = loader_length |> protocol.device

    training_log = DMTrainingLog(
        zeros(Float64,protocol.epochs),
        zeros(Float64,protocol.epochs)
    )

    if print_log; println("Training Diffusion Model... (β = $β)") end
    for epoch in 1:protocol.epochs
        epoch_loss = 0f0
        total_grad_norm = 0f0

        if epoch % 100 == 0 && protocol.shuffle
            loader = Flux.DataLoader(
                shuffleobs(training_data_device), 
                batchsize = batchsize_device, 
                shuffle = false,
                parallel = true
            )
        end

        for x₀ in loader
            b_size = size(x₀, 2)

            t_raw = rand(1:schedule.T, b_size)
            xₜ, ϵ_true = forward_diffusion(schedule, x₀, t_raw)

            loss, grads = Flux.withgradient(model) do m
                ϵ_pred = m.denoiser_model(xₜ)
                Flux.Losses.mse(ϵ_pred, ϵ_true) / (loader_length_device * size(x₀,2))
            end

            raw_gradient_arrays = Optimisers.trainables(grads[1])
            batch_grad_norm = sqrt(sum(sum(abs2, g) for g in raw_gradient_arrays if g isa AbstractArray))

            Flux.update!(opt_state, model, grads[1])
            epoch_loss += loss
            total_grad_norm += batch_grad_norm
        end

        training_log.loss[epoch] = epoch_loss
        training_log.loss_grad_norm[epoch] = total_grad_norm

        if epoch % 5 == 0 || epoch == 1
            println("Epoch: $epoch | Mean MSE Loss: $(epoch_loss / num_batches)")
        end
    end
    if print_log; println("Training complete!") end

    model = model_train_device |> cpu_device()
    Flux.loadmodel!(protocol.denoiser_model, model.denoiser_model)

    return training_log
end

function (protocol::SurrogateProtocolDM)(n_samples::Int)
    x = randn(Float64,n_samples,size(protocol.training_data,1))

    model = DiffusionModel(
        protocol.T,
        protocol.β,
        protocol.denoiser_model,
        protocol.device
    )

    for t in protocol.T:-1:1
        ϵ_pred = model.denoiser_model(x)
        βₜ = model.β[t]
        αₜ = model.α[t]
        ᾱₜ = model.ᾱ[t]

        coeff = βₜ / sqrt(1.0 - ᾱₜ)
        σₜ = sqrt(βₜ)
        μₜ = (1.0 / sqrt(αₜ)) .* (x .- coeff .* ϵ_pred)

        if t > 1
            z = randn(Float64, size(x))
            x = μₜ .+ σₜ .* z
        else
            x = μₜ
        end
    end

    return x
end

struct LayerParameters
    node_bias::Vector{Float64}
    node_weights::Matrix{Float64}
    activation_function::ActivationFunction
end

struct ChainParameters
    layers::Vector{LayerParameters}
end

struct DiffusionModelParameters
    T::Unsigned
    β::Vector{Float64}
    denoiser_model::Vector{ChainParameters}
end

function layer_parameter(layer::Dense)
    activation_function_map = Dict(
        relu => _relu,
        gelu => _gelu,
        tanh => _tanh,
        sigmoid => _sigmoid,
        softmax => _softmax,
        leakyrelu => _leakyrelu,
        elu => _elu,
        swish => _swish,
        identity => _identity
    )

    if hasproperty(layer,:σ)
        return LayerParameters(
            layer.bias,
            layer.weight,
            activation_function_map[layer.σ]
        )
    end

    return LayerParameters(
        layer.bias,
        layer.weight,
        activation_function_map[identity]
    )
end

function layer_parameter(layer::LayerParameters)
    activation_function_map = Dict(
        _relu => relu,
        _gelu => gelu,
        _tanh => tanh,
        _sigmoid => sigmoid,
        _softmax => softmax,
        _leakyrelu => leakyrelu,
        _elu => elu,
        _swish => swish,
        _identity => identity
    )

    return Dense(layer.node_weights, layer.node_bias, activation_function_map[layer.activation_function])
end

function chain_parameters(chain::Chain)
    layers = Vector{LayerParameters}(undef, length(chain))
    for i in eachindex(chain)
        layers[i] = layer_parameter(chain[i])
    end

    return ChainParameters(layers)
end

function diffusion_model_parameters(prot::SurrogateProtocolDM)
    return DiffusionModelParameters(
        prot.T,
        prot.β,
        chain_parameters(prot.denoiser_model)
    )
end

